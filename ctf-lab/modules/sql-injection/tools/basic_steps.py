# ---------- 台阶 1：让程序说话 ----------
# print = 打印（让程序把东西显示在屏幕上）
print('你好，Python！这是你的第一个程序')
print('----- 台阶1完成：你看到这句话就说明 Python 能跑了 -----')

# ---------- 台阶 2：让程序发一个 HTTP 请求 ----------
# urllib = Python 自带的'发信员'，urlopen = 寄信并收信
import urllib.request

# 去 si5b 问一下 id=1 的商品（现在先手动把地址写死）
resp = urllib.request.urlopen('http://localhost:8083/si5b/?id=1').read().decode()
print('页面内容长度：', len(resp), '个字符')
print('----- 台阶2完成：你的程序刚刚访问了靶场！ -----')

# ---------- 台阶 3：让程序会'判断' ----------
# in = 判断'某段文字在不在里面'；if/else = 如果/否则
if '查询到了' in resp:
    print('页面说：查到了 → 条件成立（True）')
else:
    print('页面说：没查到 → 条件不成立（False）')
print('----- 台阶3完成：你的程序会做判断题了 -----')

# ---------- 台阶 4：让程序'循环' ----------
# for ... in range(1, 6) = 让程序重复做 5 次（第1次到第5次）
for pos in range(1, 6):
    print('现在是第', pos, '次循环')
print('----- 台阶4完成：你的程序会重复干活了 -----')

